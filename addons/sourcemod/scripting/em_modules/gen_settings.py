"""Generate em_modules/settings.sp: save/load every menu setting of every mode to settings.cfg.

A "setting" is a global the module's menu handlers change by cycling or toggling it
(g_X = !g_X, g_X = Next*(...), g_X = (g_X + 1) % N, g_X = next, g_X = g_X >= ...). The on/off state of
the modes themselves is left out on purpose: modes always start off.
"""
import re
import sys
from pathlib import Path

root = Path(sys.argv[1])
mods = root / "em_modules"
SKIP = {"common", "integrations", "physics", "settings", "fog", "roulette"}

texts = {f.stem: f.read_text() for f in sorted(mods.glob("*.sp")) if f.stem not in SKIP}
alltext = "\n".join(texts.values()) + (mods / "roulette.sp").read_text()

# the modes' own on/off switches
mode_state = set(re.findall(r"bool \w+_IsOn\(\)\s*\{\s*return (g_\w+);", alltext))
mode_state |= {"g_VipOn", "g_HbOn", "g_RoOn", "g_Active"}

assign = re.compile(
    r"\b(g_[A-Za-z0-9]+)\s*=\s*(?:!\1\b|Next(?:Int|Float|Step)\(|\(\1 \+ 1\) %|next;|\1 >= )")
decl = re.compile(r"^(bool|int|float) (g_[A-Za-z0-9]+)\b(?!\[)", re.M)

sections = []
for stem, text in texts.items():
    types = {name: typ for typ, name in decl.findall(text)}
    found = []
    for name in assign.findall(text):
        if name in mode_state or name in found:
            continue
        if name not in types:
            continue   # an array element or declared elsewhere
        found.append(name)
    if found:
        sections.append((stem, [(n, types[n]) for n in found]))

out = ["""// Saved settings for eventmodes.sp - GENERATED by gen_settings.py from the modes' menus, don't edit by hand.
//
// Every setting an admin can change in a mode's menu is written to configs/eventmodes/settings.cfg
// (automatically at every map change and when the plugin unloads, or with "Save settings now"), and read
// back when the server starts and at every map start. The modes themselves always start switched off.

#if defined _em_settings_included
 #endinput
#endif
#define _em_settings_included

// SETTINGS_FILE is defined in common.sp (the menu uses it too).

bool Settings_Save()
{
	char path[PLATFORM_MAX_PATH], dir[PLATFORM_MAX_PATH];
	BuildPath(Path_SM, dir, sizeof(dir), "configs/eventmodes");
	if (!DirExists(dir))
		CreateDirectory(dir, 511);
	BuildPath(Path_SM, path, sizeof(path), SETTINGS_FILE);
	KeyValues kv = new KeyValues("EventModes");
"""]
for stem, items in sections:
    out.append(f'\tkv.JumpToKey("{stem}", true);\n')
    for name, typ in items:
        key = name[2:]
        if typ == "bool":
            out.append(f'\tkv.SetNum("{key}", {name} ? 1 : 0);\n')
        elif typ == "float":
            out.append(f'\tkv.SetFloat("{key}", {name});\n')
        else:
            out.append(f'\tkv.SetNum("{key}", {name});\n')
    out.append("\tkv.GoBack();\n")
out.append("""	kv.JumpToKey("roulette", true);
	kv.SetNum("RoPerRound", g_RoPerRound);
	kv.SetNum("RoNoRepeat", g_RoNoRepeat ? 1 : 0);
	kv.SetNum("RoShuffle", g_RoShuffle);
	char pool[RO_COUNT + 1];
	for (int m = 0; m < RO_COUNT; m++)
		pool[m] = g_RoPool[m] ? '1' : '0';
	pool[RO_COUNT] = '\\0';
	kv.SetString("RoPool", pool);
	kv.GoBack();
	bool ok = kv.ExportToFile(path);
	delete kv;
	return ok;
}

bool Settings_Load()
{
	char path[PLATFORM_MAX_PATH];
	BuildPath(Path_SM, path, sizeof(path), SETTINGS_FILE);
	KeyValues kv = new KeyValues("EventModes");
	if (!kv.ImportFromFile(path))
	{
		delete kv;
		return false;
	}
""")
for stem, items in sections:
    out.append(f'\tif (kv.JumpToKey("{stem}"))\n\t{{\n')
    for name, typ in items:
        key = name[2:]
        if typ == "bool":
            out.append(f'\t\t{name} = kv.GetNum("{key}", {name} ? 1 : 0) != 0;\n')
        elif typ == "float":
            out.append(f'\t\t{name} = kv.GetFloat("{key}", {name});\n')
        else:
            out.append(f'\t\t{name} = kv.GetNum("{key}", {name});\n')
    out.append("\t\tkv.GoBack();\n\t}\n")
out.append("""	if (kv.JumpToKey("roulette"))
	{
		g_RoPerRound = kv.GetNum("RoPerRound", g_RoPerRound);
		g_RoNoRepeat = kv.GetNum("RoNoRepeat", g_RoNoRepeat ? 1 : 0) != 0;
		g_RoShuffle = kv.GetNum("RoShuffle", g_RoShuffle);
		if (g_RoShuffle < 0 || g_RoShuffle >= sizeof(g_RoShuffleMin))
			g_RoShuffle = 0;
		char pool[RO_COUNT + 1];
		kv.GetString("RoPool", pool, sizeof(pool), "");
		for (int m = 0; m < RO_COUNT && pool[m] != '\\0'; m++)
			g_RoPool[m] = pool[m] == '1';
		kv.GoBack();
	}
	delete kv;
	return true;
}
""")
(mods / "settings.sp").write_text("".join(out), newline="\n")
total = sum(len(i) for _, i in sections)
print(f"{len(sections)} modules, {total} settings")
for stem, items in sections:
    print(f"  {stem}: " + ", ".join(n for n, _ in items))
